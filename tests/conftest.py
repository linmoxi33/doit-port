"""Shared fixtures.

Tests drive the *real* doit runner through ``DoitMain`` rather than calling the
hook directly wherever a behaviour depends on doit's own ordering (uptodate
hooks run before the target-existence check, actions run before
``value_savers``). Anything that only tests our arithmetic is unit tested
without doit.

Execution counting is done by the actions themselves: every action appends its
task name to ``runs.log``. That survives subprocess sandboxing, redirects and
verbosity changes, and it cannot be fooled by parsing doit's console output.
"""

from __future__ import annotations

import importlib.util
import itertools
import sys
import uuid
from pathlib import Path
from typing import Any

import pytest

from doit_port.context import PortContext

DODO_HEADER = '''
"""Generated by the test-suite -- do not edit."""
import json
import os
import pathlib

from doit_port import port_task

RUNLOG = pathlib.Path("runs.log")


def _rec(name):
    with RUNLOG.open("a", encoding="utf-8") as fh:
        fh.write(name + "\\n")


def _emit(name, output, payload):
    def act():
        _rec(name)
        parent = os.path.dirname(output)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(output, "w", encoding="utf-8", newline="\\n") as fh:
            fh.write(payload() if callable(payload) else payload)
        return None
    return act
'''


PIPELINE_DODO = DODO_HEADER + '''

def _first_line(path):
    with open(path, encoding="utf-8") as fh:
        return fh.readline().strip()


def task_collect():
    """src/input.txt -> build/rows.txt (first line only)."""
    return port_task(
        basename="collect",
        actions=[_emit("collect", "build/rows.txt",
                       lambda: _first_line("src/input.txt"))],
        targets=["build/rows.txt"],
        inputs=["src/input.txt"],
        doc="take the first line of the source",
    )


def task_summarize():
    """build/rows.txt -> build/summary.json"""
    def act():
        _rec("summarize")
        text = pathlib.Path("build/rows.txt").read_text(encoding="utf-8").strip()
        payload = {"chars": len(text), "words": len(text.split()), "text": text}
        pathlib.Path("build").mkdir(parents=True, exist_ok=True)
        pathlib.Path("build/summary.json").write_text(
            json.dumps(payload, sort_keys=True), encoding="utf-8")
        return None

    return port_task(
        basename="summarize",
        actions=[act],
        targets=["build/summary.json"],
        inputs=["build/rows.txt"],
        task_dep=["collect"],
        doc="measure the collected row",
    )


def task_report():
    """build/summary.json -> build/report.md"""
    def act():
        _rec("report")
        data = json.loads(pathlib.Path("build/summary.json").read_text(encoding="utf-8"))
        text = "# report\\n\\n- chars: {chars}\\n- words: {words}\\n".format(**data)
        pathlib.Path("build").mkdir(parents=True, exist_ok=True)
        pathlib.Path("build/report.md").write_text(text, encoding="utf-8")
        return None

    return port_task(
        basename="report",
        actions=[act],
        targets=["build/report.md"],
        inputs=["build/summary.json"],
        task_dep=["summarize"],
        doc="render the markdown report",
    )
'''


_counter = itertools.count()


def load_dodo(project: Path):
    """Import ``project/dodo.py`` as a throwaway module."""
    name = f"_dodo_{next(_counter)}_{uuid.uuid4().hex[:6]}"
    spec = importlib.util.spec_from_file_location(name, project / "dodo.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def run_doit(project: Path, *args: str) -> int:
    """Run doit inside *project* and return its exit code.

    ``PortContext`` is process-wide; resetting it here makes each call behave
    like a fresh ``doit`` process, which is what the cross-machine tests need.
    The working directory is switched because both doit and doit-port resolve
    ``dodo.py`` / ``doit-port.toml`` against it.
    """
    import os

    from doit.cmd_base import ModuleTaskLoader
    from doit.doit_cmd import DoitMain

    old_cwd = os.getcwd()
    project = Path(project).resolve()
    PortContext.reset()
    os.chdir(project)
    try:
        module = load_dodo(project)
        main = DoitMain(ModuleTaskLoader(module))
        return main.run(list(args) if args else [])
    finally:
        os.chdir(old_cwd)
        PortContext.reset()


def read_runs(project: Path) -> list[str]:
    log = project / "runs.log"
    if not log.is_file():
        return []
    return [line.strip() for line in log.read_text(encoding="utf-8").splitlines() if line.strip()]


def clear_runs(project: Path) -> None:
    (project / "runs.log").unlink(missing_ok=True)


